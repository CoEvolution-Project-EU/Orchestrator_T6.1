// src/controllers/minio.controller.js
// Handles file operations for all MinIO pools

import { getPool } from '../config/minio.js'
import { File } from '../models/file.model.js'

// ── Upload a file ─────────────────────────────────────────────
// POST /api/v1/files/upload
// Body: multipart/form-data with fields: pool, bucket, modelName, tags
// File: the actual file via multer

const uploadFile = async (req, res) => {
  try {
    const { pool, bucket, model_uuid, version, tags } = req.body  // ← correct
    const file = req.file  // from multer middleware

    if (!pool || !bucket || !model_uuid || !version || !file) {
      return res.status(400).json({ message: 'pool, bucket and file are required' })
    }

    const client =  getPool(pool)
    if (!client) {
      return res.status(400).json({ message: `Unknown pool: ${pool}` })
    }

    // Generate unique object key
    const objectKey = `${Date.now()}-${file.originalname}`

    // Upload to MinIO
    await client.putObject(
      bucket,
      objectKey,
      file.buffer,
      file.size,
      { 'Content-Type': file.mimetype }
    )

    // Save metadata to MongoDB
    const doc = await File.create({
      pool,          // ✓ required in schema — comes from req.body
      bucket,        // ✓ required in schema — comes from req.body
      model_uuid,    // ✓ required in schema — comes from req.body
      version,       // ✓ required in schema — comes from req.body
      objectKey,     // ✓ required in schema — generated by backend
      filename:    file.originalname,  // ✓ optional in schema
      size:        file.size,          // ✓ optional in schema
      contentType: file.mimetype,      // ✓ optional in schema
      uploadedBy:  req.user?.username || 'backend',  // ✓ optional in schema
      tags:        tags ? tags.split(',').map(t => t.trim()) : [],  // ✓ optional in schema
    })

    res.status(201).json({
      message: 'File uploaded successfully',
      file: doc,
    })
  } catch (error) {
    res.status(500).json({ message: 'Upload failed', error: error.message })
  }
}

// ── Download a file ───────────────────────────────────────────
// GET /api/v1/files/download/:id
const downloadFile = async (req, res) => {
  try {
    const doc = await File.findById(req.params.id)
    if (!doc) return res.status(404).json({ message: 'File not found' })

    const client = getPool(doc.pool)    // ← fix: was minioPools[doc.pool]
    const stream = await client.getObject(doc.bucket, doc.objectKey)

    res.setHeader('Content-Type', doc.contentType)
    res.setHeader('Content-Disposition', `attachment; filename="${doc.filename}"`)
    stream.pipe(res)
  } catch (error) {
    res.status(500).json({ message: 'Download failed', error: error.message })
  }
}

// ── Get presigned URL (temporary download link) ───────────────
// GET /api/v1/files/url/:id
const getPresignedUrl = async (req, res) => {
  try {
    const doc = await File.findById(req.params.id)
    if (!doc) return res.status(404).json({ message: 'File not found' })

    const client = getPool(doc.pool)    // ← fix: was minioPools[doc.pool]
    const url = await client.presignedGetObject(doc.bucket, doc.objectKey, 3600)

    res.status(200).json({ url, expiresIn: '1 hour' })
  } catch (error) {
    res.status(500).json({ message: 'Failed to generate URL', error: error.message })
  }
}

// ── Search files ──────────────────────────────────────────────
// GET /api/v1/files/search?modelName=gpt-4&pool=AP&uploadedBy=partner1
const searchFiles = async (req, res) => {
  try {
    const { modelName, pool, bucket, uploadedBy, tags, from, to } = req.query
    const query = {}

    if (modelName)  query.modelName  = modelName
    if (pool)       query.pool       = pool
    if (bucket)     query.bucket     = bucket
    if (uploadedBy) query.uploadedBy = uploadedBy
    if (tags)       query.tags       = { $in: tags.split(',') }
    if (from || to) {
      query.uploadedAt = {}
      if (from) query.uploadedAt.$gte = new Date(from)
      if (to)   query.uploadedAt.$lte = new Date(to)
    }

    const files = await File.find(query).sort({ uploadedAt: -1 }).limit(100)
    res.status(200).json({ count: files.length, files })
  } catch (error) {
    res.status(500).json({ message: 'Search failed', error: error.message })
  }
}

// ── List all files in a pool/bucket ──────────────────────────
// GET /api/v1/files?pool=AP&bucket=assessments
const listFiles = async (req, res) => {
  try {
    const { pool, bucket } = req.query
    const query = {}
    if (pool)   query.pool   = pool
    if (bucket) query.bucket = bucket

    const files = await File.find(query).sort({ uploadedAt: -1 })
    res.status(200).json({ count: files.length, files })
  } catch (error) {
    res.status(500).json({ message: 'List failed', error: error.message })
  }
}

// ── Delete a file ─────────────────────────────────────────────
// DELETE /api/v1/files/:id
const deleteFile = async (req, res) => {
  try {
    const doc = await File.findById(req.params.id)
    if (!doc) return res.status(404).json({ message: 'File not found' })

    const client = getPool(doc.pool)    // ← fix: was minioPools[doc.pool]
    await client.removeObject(doc.bucket, doc.objectKey)

    await File.findByIdAndDelete(req.params.id)
    res.status(200).json({ message: 'File deleted successfully' })
  } catch (error) {
    res.status(500).json({ message: 'Delete failed', error: error.message })
  }
}

export {
  uploadFile,
  downloadFile,
  getPresignedUrl,
  searchFiles,
  listFiles,
  deleteFile,
}