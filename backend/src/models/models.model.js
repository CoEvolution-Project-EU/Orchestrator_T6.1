import mongoose, {Schema} from "mongoose";
import { v4 as uuidv4 } from 'uuid'


// Sub-schema for each version entry
const versioningSchema = new Schema(
    {
      version: {
        type: String,
        required: true,
      },
      description: {
        type: String,              // free text by user
      },
      trusted: {
        type: Boolean,
        default: false,
      },
      // below fields are continuously updated by the orchestrator
      defences: {
        type: [String],            // e.g. ["DEF-001", "DEF-002"]
        default: [],
      },
      assessments: {
        type: [String],            // e.g. ["ASM-001", "ASM-002"]
        default: [],
      },
      risk_assessment_reports: {
        type: [String],            // e.g. ["REP-001", "REP-002"]
        default: [],
      },
      gadgets_reports:{ 
        type: [String],
        default: [] 
      },
      aimodelinfo_reports: {
         type: [String], 
         default: [] 
        },
      euaiact_reports:     {
         type: [String], 
         default: [] 
        },
      datasets_reports:    {
         type: [String], 
         default: [] 
        },
      ai_mbom: {
         type: [String], 
         default: [] 
        },
      user_assessments: { type: [String], default: [] },   
      user_defences:    { type: [String], default: [] }, 
      requirements: { type: [String], default: [] },
      trusted_model: { type: [String], default: [] }, 
    },
    {
        timestamps: true
    },
    { _id: false }                 // no separate _id for each version entry
  )
// create a Schema object, a class (constructor function) that represents a MongoDB collection
const postSchema = new Schema (
    {
        name: {
            type: String,
            required: true,
            trim: true
        },
        model_uuid: {
            type: String,
            unique: true,
            default: uuidv4         // auto-generated by orchestrator on registration
        },
        owner: {
            type: String,
            required: true,
            trim: true              // Keycloak username, set on registration via UI
        },
        type: {
            type: String,
            required: true         // dropdown selection by user
        },
        model_paradigm: {
          type: String,        
        },
        architecture_family: {
          type: String,       
        },
        framework: {
          type: String,        
        },
        input_modality: {
          type:    [String],   
          default: [],
        },
        versioning: {
            type: [versioningSchema],
            required: true         // dropdown selection by user

          }
    }
) 


// create a Mongoose Model
export const Model = mongoose.model('Model', postSchema)